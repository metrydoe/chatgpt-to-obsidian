"""Build the self-contained Obsidian entry point using only Python's stdlib.

All local runtime modules are embedded in isolated CommonJS wrappers. Only
Obsidian's public API is resolved by the application's plugin loader.
"""
from pathlib import Path
import argparse,json,re

ROOT=Path(__file__).resolve().parent
MODULES={
    './archive-player':ROOT/'shared/archive-player.js',
    './dil-archive':ROOT/'extension/dil-archive.js',
    './snapshot-bindings':ROOT/'shared/snapshot-bindings.js',
    './native-widgets':ROOT/'shared/native-widgets.js',
}

def build():
    entry=(ROOT/'plugin-src/main.js').read_text(encoding='utf-8')
    for name,path in MODULES.items():
        source=path.read_text(encoding='utf-8')
        # A wrapper prevents module.exports in the embedded source from
        # replacing the plugin's own exported class.
        replacement="(()=>{\nconst module={exports:{}};const exports=module.exports;\n"+source+"\nreturn module.exports;\n})()"
        quoted=re.escape(name)
        pattern=r"\brequire\(\s*(['\"])"+quoted+r"\1\s*\)"
        entry,count=re.subn(pattern,lambda _match:replacement,entry)
        if count!=1:raise ValueError('Expected one local module import: '+name)
    dependencies=re.findall(r"\brequire\(\s*['\"]([^'\"]+)['\"]\s*\)",entry)
    if dependencies!=['obsidian']:
        raise ValueError('Unexpected external module in plugin bundle: '+repr(dependencies))
    return '// Generated by build_plugin.py. Edit plugin-src/main.js and rebuild.\n'+entry

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Fail if the installed source bundle is stale')
    args=parser.parse_args()
    target=ROOT/'obsidian-plugin/main.js';source=build()
    if args.check:
        if not target.is_file() or target.read_text(encoding='utf-8')!=source:raise SystemExit('Plugin bundle is stale; run python build_plugin.py')
    else:target.write_text(source,encoding='utf-8')
    print(json.dumps({'bundle':str(target),'bytes':len(source.encode()),'external_modules':['obsidian'],'check':args.check}))

if __name__=='__main__':main()
